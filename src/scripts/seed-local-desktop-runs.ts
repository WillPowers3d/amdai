function card(partial: Omit<RunCard, 'schema' | 'submitted_by' | 'started_at' | 'finished_at' | 'measured'> & {
  submitted_by?: RunCard['submitted_by'];
  started_at?: string | null;
  finished_at?: string | null;
  measured?: boolean;
}): RunCard {
  return emitRunCard({
    submitted_by: { ...amdai },
    started_at: null,
    finished_at: null,
    measured: true,
    ...partial,
  });
}

